-- Schema for the demo. Hibernate also creates these tables (ddl-auto=create);
-- IF NOT EXISTS keeps this script harmless when run after JPA initialization.
CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    balance DECIMAL(19, 2) NOT NULL
);
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    txn_date DATE NOT NULL,
    description VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL,
    budget_month INT NOT NULL,
    budget_year INT NOT NULL,
    amount DECIMAL(19, 2) NOT NULL
);
CREATE TABLE IF NOT EXISTS savings_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    target_amount DECIMAL(19, 2) NOT NULL,
    saved_amount DECIMAL(19, 2) NOT NULL,
    deadline DATE
);
CREATE TABLE IF NOT EXISTS holdings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    shares DECIMAL(19, 4) NOT NULL,
    purchase_price DECIMAL(19, 2) NOT NULL,
    current_price DECIMAL(19, 2) NOT NULL
);
